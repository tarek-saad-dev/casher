import {beforeAll,afterAll,describe,it,expect,vi} from 'vitest';
import sql from 'mssql';
vi.mock('server-only',()=>({}));
import {pilotTenant} from '@/lib/cut-club/membershipDraft';
import {saveMembershipDraft} from '@/lib/cut-club/membershipDraftSql';
import {publishMembership} from '@/lib/cut-club/membershipPublicationSql';
import {saveBenefitDraft} from '@/lib/cut-club/membershipBenefitDraftSql';
import {recordBenefitApproval,listBenefitApprovals} from '@/lib/cut-club/membershipBenefitApprovalSql';
const enabled=process.env.CI==='true'&&process.env.MEMBERSHIP_EPHEMERAL_SQL==='1'&&process.env.MEMBERSHIP_EPHEMERAL_HOST==='127.0.0.1'&&!process.env.DB_SERVER&&!process.env.CLOUD_DB_SERVER;
const scope={tenantId:pilotTenant,staffId:71};
const program={code:'APPROVAL_SQL',expectedRevision:0,title:'Synthetic approval',kind:'GENERAL',minimumVisits:0,allowedBranchIds:[1],partnerCode:null,reason:'fixture only'};
const rule={code:'HAIR',kind:'PERCENT_DISCOUNT',serviceId:9,value:1000,maxUsesPerMembership:3,maxUsesPerInvoice:1,branchIds:[1]};
const draft={programCode:program.code,programRevision:1,expectedRevision:0,reason:'proposal only',rules:[rule]};
const cmd={action:'APPROVE',programCode:program.code,programRevision:1,publicationRevision:1,benefitRevision:1,expectedRevision:0,reason:'review complete'};
let pool:sql.ConnectionPool;
describe.skipIf(!enabled)('benefit approval history, disposable SQL only',()=>{
 beforeAll(async()=>{
 const password=process.env.MEMBERSHIP_EPHEMERAL_AGENT;if(!password)throw Error('MISSING_TEST_LOGIN');
 pool=await new sql.ConnectionPool({server:'127.0.0.1',port:1433,database:'last132_agent',user:'drvo_agent',password,options:{encrypt:false,trustServerCertificate:true},pool:{max:6,min:0}}).connect();
 const c=await pool.request().query('SELECT DB_NAME() AS Db,SUSER_SNAME() AS LoginName');
 if(c.recordset[0]?.Db!=='last132_agent'||c.recordset[0]?.LoginName!=='drvo_agent')throw Error('WRONG_DB');
 for(const k of ['DRAFT','PUBLICATION','BENEFIT_DRAFT','BENEFIT_APPROVAL'])process.env['CUT_CLUB_STAGING_MEMBERSHIP_'+k+'_ENABLED']='true';
 });
 afterAll(async()=>{await pool?.close();});
 it('requires publication, validates live catalog, pins revisions, rejects duplicates and records revocation',async()=>{
 await saveMembershipDraft(pool,scope,program);
 await saveBenefitDraft(pool,scope,draft);
 await expect(recordBenefitApproval(pool,scope,cmd)).rejects.toMatchObject({code:'PROGRAM_NOT_CURRENT'});
 await publishMembership(pool,scope,{action:'PUBLISH',code:program.code,programRevision:1,expectedRevision:0,reason:'publish test'});
 const results=await Promise.allSettled([recordBenefitApproval(pool,scope,cmd),recordBenefitApproval(pool,scope,cmd)]);
 expect(results.filter(x=>x.status==='fulfilled')).toHaveLength(1);
 expect(results.find(x=>x.status==='rejected')).toMatchObject({reason:{code:'APPROVAL_REVISION_CONFLICT'}});
 const current=async()=>(await listBenefitApprovals(pool,scope)).find(x=>x.programCode===program.code);
 expect(await current()).toMatchObject({revision:1,benefitRevision:1,status:'APPROVED_FOR_TEST'});
 await saveBenefitDraft(pool,scope,{...draft,expectedRevision:1,rules:[{...rule,kind:'FIXED_PRICE',value:25000}],reason:'invalid price draft'});
 expect(await current()).toMatchObject({revision:1,benefitRevision:1,status:'APPROVED_FOR_TEST'});
 await expect(recordBenefitApproval(pool,scope,{...cmd,expectedRevision:1,benefitRevision:2})).rejects.toMatchObject({code:'BENEFIT_CATALOG_OR_PRICE_INVALID'});
 await saveBenefitDraft(pool,scope,{...draft,expectedRevision:2,rules:[{...rule,serviceId:12}],reason:'foreign service draft'});
 await expect(recordBenefitApproval(pool,scope,{...cmd,expectedRevision:1,benefitRevision:3})).rejects.toMatchObject({code:'BENEFIT_CATALOG_OR_PRICE_INVALID'});
 await saveBenefitDraft(pool,scope,{...draft,expectedRevision:3,rules:[{...rule,value:2000}],reason:'new valid draft'});
 await recordBenefitApproval(pool,scope,{...cmd,expectedRevision:1,benefitRevision:4});
 expect(await current()).toMatchObject({revision:2,benefitRevision:4,status:'APPROVED_FOR_TEST'});
 await publishMembership(pool,scope,{action:'WITHDRAW',code:program.code,programRevision:1,expectedRevision:1,reason:'withdraw test'});
 expect(await current()).toMatchObject({status:'SUPERSEDED'});
 await recordBenefitApproval(pool,{...scope,staffId:72},{...cmd,action:'REVOKE',expectedRevision:2,benefitRevision:4,reason:'revoke test'});
 expect(await current()).toMatchObject({revision:3,status:'REVOKED'});
 const history=await pool.request().input('tenant',sql.UniqueIdentifier,pilotTenant).input('code',sql.VarChar(40),program.code).query('SELECT Revision,Action,StaffID,CatalogJson FROM dbo.CutClubMembershipBenefitApproval WHERE TenantId=@tenant AND ProgramCode=@code ORDER BY Revision');
 expect(history.recordset.map(x=>({rev:x.Revision,action:x.Action,staff:x.StaffID}))).toEqual([{rev:1,action:'APPROVE',staff:71},{rev:2,action:'APPROVE',staff:71},{rev:3,action:'REVOKE',staff:72}]);
 expect(JSON.parse(history.recordset[0].CatalogJson)).toEqual([{serviceId:9,name:'حلاقة',priceMinor:20001}]);
 process.env.CUT_CLUB_STAGING_MEMBERSHIP_BENEFIT_APPROVAL_ENABLED='false';
 await expect(listBenefitApprovals(pool,scope)).rejects.toMatchObject({code:'BENEFIT_APPROVAL_NOT_RELEASED'});
 });
});
